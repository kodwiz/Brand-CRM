"""Render any report payload (see report_service) as an Excel workbook or a PDF. The renderers know nothing about individual reports: they draw the title block,
the filters, the table, the totals, the reconciliation and the notes exactly as the screen shows them, so a file always matches what was on screen."""
from __future__ import annotations

import io
import re
from datetime import datetime
from decimal import Decimal, InvalidOperation

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

ACCENT = "9B6B7C"
MAX_ROWS = 50_000
_NUM = re.compile(r"^-?[\d,]*\.?\d+$")


def _num(v):
    """Numbers stay numbers in Excel so they can be summed; everything else stays text."""
    if isinstance(v, (int, float, Decimal)) and not isinstance(v, bool):
        return v
    if isinstance(v, str) and _NUM.match(v.strip()):
        try:
            d = Decimal(v.replace(",", ""))
        except InvalidOperation:
            return v
        return int(d) if d == d.to_integral_value() and "." not in v else float(d)
    return v


def _put(ws, r: int, j: int, v):
    """Write a cell; text that starts with '=' is stored as text so a customer or item name can never run as a spreadsheet formula."""
    c = ws.cell(r, j, v)
    if isinstance(v, str) and v.startswith("="):
        c.data_type = "s"
    return c


def _label(k: str) -> str:
    return k.replace("_", " ").capitalize()


def _fmt_total(v) -> str:
    if isinstance(v, bool):
        return "Yes" if v else "No"
    return str(v)


def filename(rep: dict, ext: str) -> str:
    base = re.sub(r"[^A-Za-z0-9]+", "-", rep.get("title", "report")).strip("-").lower() or "report"
    return f"{base}-{datetime.now():%Y%m%d}.{ext}"


def _meta_lines(rep: dict) -> list[str]:
    out = []
    if rep.get("subtitle"):
        out.append(rep["subtitle"])
    if rep.get("filters"):
        out.append("Filters: " + ", ".join(f"{k} = {v}" for k, v in rep["filters"].items()))
    if rep.get("generated_by"):
        out.append(f"Generated by {rep['generated_by']} on {rep.get('generated_at', '')[:16].replace('T', ' ')} UTC")
    return out


# ---- Excel -----------------------------------------------------------------------------------------------------------------------------------
def to_xlsx(rep: dict) -> bytes:
    rows = rep["rows"][:MAX_ROWS]
    wb = Workbook()
    ws = wb.active
    ws.title = re.sub(r"[\[\]\*\?/\\:]", " ", rep["title"])[:31]
    thin = Side(style="thin", color="DDD6D0")
    r = 1
    ws.cell(r, 1, rep["title"]).font = Font(bold=True, size=14)
    r += 1
    for line in _meta_lines(rep):
        ws.cell(r, 1, line).font = Font(color="6B6560", size=10)
        r += 1
    r += 1
    cols = rep["columns"]
    for j, c in enumerate(cols, 1):
        cell = ws.cell(r, j, c["label"])
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor=ACCENT)
        cell.alignment = Alignment(horizontal="right" if c.get("align") == "right" else "left", vertical="center", wrap_text=True)
    head_row = r
    r += 1
    for row in rows:
        for j, c in enumerate(cols, 1):
            v = row.get(c["key"], "")
            cell = _put(ws, r, j, _num(v) if c.get("align") == "right" else ("" if v is None else v))
            cell.border = Border(bottom=thin)
            if c.get("align") == "right":
                cell.alignment = Alignment(horizontal="right")
                if isinstance(cell.value, float):
                    cell.number_format = "#,##0.00"
                elif isinstance(cell.value, int) and not isinstance(cell.value, bool):
                    cell.number_format = "#,##0"
        r += 1
    if len(rep["rows"]) > MAX_ROWS:
        ws.cell(r, 1, f"Only the first {MAX_ROWS:,} rows are included. Narrow the filters to see the rest.").font = Font(italic=True, color="B00020")
        r += 1
    if rep.get("totals"):
        r += 1
        ws.cell(r, 1, "Totals").font = Font(bold=True)
        r += 1
        for k, v in rep["totals"].items():
            ws.cell(r, 1, _label(k))
            val = _num(v) if not isinstance(v, bool) else _fmt_total(v)
            c = ws.cell(r, 2, val)
            c.font = Font(bold=True)
            c.alignment = Alignment(horizontal="right")
            if isinstance(val, float):
                c.number_format = "#,##0.00"
            r += 1
    if rep.get("reconciliation"):
        r += 1
        ws.cell(r, 1, "Reconciliation to the ledger").font = Font(bold=True)
        r += 1
        for j, h in enumerate(("Check", "This report", "Ledger", "Difference", "Agrees"), 1):
            ws.cell(r, j, h).font = Font(bold=True)
        r += 1
        for x in rep["reconciliation"]:
            for j, v in enumerate((x["label"], _num(x["report"]), _num(x["ledger"]), _num(x["difference"]), "Yes" if x["agrees"] else "NO - see note"), 1):
                ws.cell(r, j, v)
            r += 1
            if x.get("note"):
                ws.cell(r, 1, x["note"]).font = Font(italic=True, color="6B6560", size=9)
                r += 1
    if rep.get("notes"):
        r += 1
        ws.cell(r, 1, "Notes").font = Font(bold=True)
        r += 1
        for n in rep["notes"]:
            ws.cell(r, 1, n).font = Font(color="6B6560", size=10)
            r += 1
    for j, c in enumerate(cols, 1):
        longest = max([len(str(c["label"]))] + [len(str(x.get(c["key"], ""))) for x in rows[:300]])
        ws.column_dimensions[get_column_letter(j)].width = min(max(longest + 2, 10), 46)
    ws.freeze_panes = ws.cell(head_row + 1, 1)
    ws.sheet_view.showGridLines = False
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


# ---- PDF -------------------------------------------------------------------------------------------------------------------------------------
def to_pdf(rep: dict) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    cols = rep["columns"]
    rows = rep["rows"][:MAX_ROWS]
    wide = len(cols) > 6
    page = landscape(A4) if wide else A4
    buf = io.BytesIO()
    margin = 14 * mm
    doc = SimpleDocTemplate(buf, pagesize=page, leftMargin=margin, rightMargin=margin, topMargin=14 * mm, bottomMargin=16 * mm, title=rep["title"], author=rep.get("generated_by", ""))
    ss = getSampleStyleSheet()
    accent = colors.HexColor("#" + ACCENT)
    title = ParagraphStyle("t", parent=ss["Title"], alignment=0, fontSize=16, textColor=colors.HexColor("#2B2724"), spaceAfter=2)
    meta = ParagraphStyle("m", parent=ss["Normal"], fontSize=8.5, textColor=colors.HexColor("#6B6560"), leading=11)
    cell = ParagraphStyle("c", parent=ss["Normal"], fontSize=7.5, leading=9.5)
    cell_r = ParagraphStyle("cr", parent=cell, alignment=2)
    head = ParagraphStyle("h", parent=cell, textColor=colors.white, fontName="Helvetica-Bold")
    head_r = ParagraphStyle("hr", parent=head, alignment=2)
    small = ParagraphStyle("s", parent=ss["Normal"], fontSize=8, leading=10.5, textColor=colors.HexColor("#4A4540"))
    bold = ParagraphStyle("b", parent=small, fontName="Helvetica-Bold", spaceBefore=8, spaceAfter=2)

    def esc(v) -> str:
        return str("" if v is None else v).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    story = [Paragraph(esc(rep["title"]), title)]
    for line in _meta_lines(rep):
        story.append(Paragraph(esc(line), meta))
    story.append(Spacer(1, 6))
    avail = page[0] - 2 * margin
    weights = []
    for c in cols:
        sample = [len(str(c["label"]))] + [len(str(x.get(c["key"], ""))) for x in rows[:200]]
        weights.append(min(max(max(sample), 6), 34 if c.get("align") != "right" else 16))
    widths = [avail * w / sum(weights) for w in weights]
    data = [[Paragraph(esc(c["label"]), head_r if c.get("align") == "right" else head) for c in cols]]
    for x in rows:
        data.append([Paragraph(esc(x.get(c["key"], "")), cell_r if c.get("align") == "right" else cell) for c in cols])
    if len(data) == 1:
        data.append([Paragraph("No records for these filters.", cell)] + [""] * (len(cols) - 1))
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), accent), ("VALIGN", (0, 0), (-1, -1), "TOP"), ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F7F4F1")]),
                           ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#DDD6D0")), ("TOPPADDING", (0, 0), (-1, -1), 2.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5)]))
    story.append(t)
    if len(rep["rows"]) > MAX_ROWS:
        story.append(Paragraph(f"Only the first {MAX_ROWS:,} rows are included. Narrow the filters to see the rest.", small))
    if rep.get("totals"):
        story.append(Paragraph("Totals", bold))
        tt = Table([[Paragraph(esc(_label(k)), small), Paragraph(esc(_fmt_total(v)), ParagraphStyle("tv", parent=small, alignment=2, fontName="Helvetica-Bold"))] for k, v in rep["totals"].items()],
                   colWidths=[avail * 0.35, avail * 0.2], hAlign="LEFT")
        tt.setStyle(TableStyle([("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#DDD6D0")), ("TOPPADDING", (0, 0), (-1, -1), 1.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 1.5)]))
        story.append(tt)
    if rep.get("reconciliation"):
        story.append(Paragraph("Reconciliation to the ledger", bold))
        rc = [[Paragraph(h, head_r if i else head) for i, h in enumerate(("Check", "This report", "Ledger", "Difference", "Agrees"))]]
        for x in rep["reconciliation"]:
            rc.append([Paragraph(esc(x["label"]), cell), Paragraph(esc(x["report"]), cell_r), Paragraph(esc(x["ledger"]), cell_r), Paragraph(esc(x["difference"]), cell_r),
                       Paragraph("Yes" if x["agrees"] else "NO - see note", cell_r)])
        rt = Table(rc, colWidths=[avail * 0.4] + [avail * 0.15] * 4, hAlign="LEFT")
        rt.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), accent), ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#DDD6D0"))]))
        story.append(rt)
        for x in rep["reconciliation"]:
            if x.get("note"):
                story.append(Paragraph(esc(x["note"]), meta))
    if rep.get("notes"):
        story.append(Paragraph("Notes", bold))
        for n in rep["notes"]:
            story.append(Paragraph("• " + esc(n), small))

    def footer(canvas, d):
        canvas.saveState()
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(colors.HexColor("#6B6560"))
        canvas.drawString(margin, 9 * mm, f"{rep['title']}  ·  generated {rep.get('generated_at', '')[:16].replace('T', ' ')} UTC")
        canvas.drawRightString(page[0] - margin, 9 * mm, f"Page {d.page}")
        canvas.restoreState()
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()
